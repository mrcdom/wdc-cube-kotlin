package com.example.tasks.persistence

import br.com.wdc.framework.jooq.JsonDialect
import java.sql.Connection
import org.jooq.SQLDialect

/**
 * The schema, created when the backend starts. `IF NOT EXISTS` keeps a database file from one run to the next; an
 * application whose schema changes over time keeps numbered migrations instead (the WDC Store's `DBCreate`).
 */
object TaskSchema {

    const val TITLE_LENGTH = 200

    const val CREATE_TASK = """
        CREATE TABLE IF NOT EXISTS TASK (
            ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            TITLE VARCHAR($TITLE_LENGTH) NOT NULL,
            DONE BOOLEAN DEFAULT FALSE NOT NULL
        )
    """

    fun create(connection: Connection) {
        // what framework-jooq's queries need from the database (functions of its own)
        JsonDialect.of(SQLDialect.H2).initialize(connection)
        connection.createStatement().use { it.execute(CREATE_TASK) }
    }
}
