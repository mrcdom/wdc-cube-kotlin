package br.com.wdc.framework.domain.codec

import br.com.wdc.framework.commons.serialization.ExtensibleObjectInput
import br.com.wdc.framework.commons.serialization.ExtensibleObjectOutput

/**
 * Serialization contract for the entities and criteria of a repository.
 *
 * Uses the streaming API of `framework-commons`, without reflection — the same codec serves client and server,
 * on every target.
 *
 * @param E entity type
 * @param C search criteria type
 */
interface ModelCodec<E, C> {

    /** Result of reading an entity for update: the entity and the projection (fields present in the JSON). */
    data class UpdateData<T>(val entity: T, val projection: T)

    /** Writes the entity as a complete JSON object (`beginObject` + fields + `endObject`). */
    fun writeEntity(out: ExtensibleObjectOutput, entity: E) = writeEntity(out, entity, EntityGraph())

    /**
     * Writes the entity with graph tracking — an entity already seen is written with the key only.
     * Implementations use [EntityGraph.track] before serializing nested fields.
     */
    fun writeEntity(out: ExtensibleObjectOutput, entity: E, graph: EntityGraph)

    /**
     * Writes only the fields indicated by the projection (non-null in it). The id is always included; a marked
     * field whose value is `null` goes out as an explicit `null`.
     */
    fun writeEntityProjected(out: ExtensibleObjectOutput, entity: E, projection: E)

    /** Projection with a sentinel in each field that differs between [newEntity] and [oldEntity]. */
    fun computeProjection(newEntity: E, oldEntity: E): E

    /** Reads an entity from the current position (expects `beginObject`). An unknown name is skipped. */
    fun readEntity(input: ExtensibleObjectInput): E

    /**
     * Reads an entity for update, also returning the projection: every field present in the JSON — including
     * the `null` ones — is marked in it. This is what allows explicitly updating a field to `null`.
     */
    fun readEntityForUpdate(input: ExtensibleObjectInput): UpdateData<E>

    /** Reads a list of entities (expects `beginArray`). */
    fun readEntityList(input: ExtensibleObjectInput): List<E> {
        val list = ArrayList<E>()
        input.beginArray()
        while (input.hasNext()) {
            list.add(readEntity(input))
        }
        input.endArray()
        return list
    }

    /** Writes the criteria fields into the current object (without `begin/endObject`). */
    fun writeCriteriaFields(out: ExtensibleObjectOutput, criteria: C)

    /**
     * Reads **one** criteria field, already positioned after the name. Returns `true` if the field was consumed;
     * `false` if it is not a recognized criteria field (the caller does `skipValue`).
     */
    fun readCriteriaField(input: ExtensibleObjectInput, fieldName: String, criteria: C): Boolean

    /** The projection associated with the criteria (may be `null`). */
    fun getProjection(criteria: C): E?

    /** Sets on the entity the id generated by the server, after the insert. */
    fun setGeneratedId(entity: E, id: Long)
}
