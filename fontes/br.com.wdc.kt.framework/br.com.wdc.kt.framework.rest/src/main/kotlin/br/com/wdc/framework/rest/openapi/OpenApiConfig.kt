package br.com.wdc.framework.rest.openapi

/** The OpenAPI document: where it is served and what doesn't come from the routes. */
class OpenApiConfig {

    /** Where the document is served (public). */
    var path: String = "/openapi.json"

    var openapiVersion: String = "3.0.3"

    var title: String = "API"
    var version: String = "1.0.0"
    var description: String? = null

    /** `servers`: the base URLs. Empty = omitted. */
    val servers = ArrayList<String>()

    /** `tags` with description, in the order they appear. */
    val tags = LinkedHashMap<String, String?>()

    /**
     * The security scheme of the protected routes, in `components.securitySchemes`. Default: Bearer JWT. `null` =
     * no scheme and no `security` on the operations.
     */
    var securityScheme: Pair<String, Map<String, Any?>>? = "bearerAuth" to mapOf("type" to "http", "scheme" to "bearer", "bearerFormat" to "JWT")

    /** Hand-written schemas, in `components.schemas` (those generated by reflection are added to them). */
    val schemas = LinkedHashMap<String, Any?>()

    /** Reusable parameters, in `components.parameters`. */
    val parameters = LinkedHashMap<String, Any?>()

    /** Raw keys at the top of the document, applied last. */
    val raw = LinkedHashMap<String, Any?>()

    /** Raw keys of `info`, applied last. */
    val info = LinkedHashMap<String, Any?>()

    internal var uiOptions: SwaggerUiOptions? = null

    /** Serves the Swagger UI page with this document (see [SwaggerUiOptions]). Requires the webjar on the classpath. */
    fun ui(block: SwaggerUiOptions.() -> Unit = {}) {
        uiOptions = (uiOptions ?: SwaggerUiOptions()).apply(block)
    }

    fun tag(name: String, description: String? = null) {
        tags[name] = description
    }
}
