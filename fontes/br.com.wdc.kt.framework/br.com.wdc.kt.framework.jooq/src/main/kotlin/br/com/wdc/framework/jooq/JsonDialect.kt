package br.com.wdc.framework.jooq

import br.com.wdc.framework.jooq.dialect.H2JsonDialect
import br.com.wdc.framework.jooq.dialect.PostgresJsonDialect
import java.sql.Connection
import org.jooq.DSLContext
import org.jooq.Field
import org.jooq.InsertReturningStep
import org.jooq.Table
import org.jooq.SQLDialect
import org.jooq.SortField

/**
 * JSON generation in native SQL, per database.
 *
 * Fields always go in as **template placeholders** (`{N}`) with the matching `QueryPart`, never as
 * concatenated text — that is what preserves the bind values of filtered subqueries.
 */
interface JsonDialect {

    /** SQL field that produces a JSON object (as text) from the entries. */
    fun jsonObject(entries: List<JsonFieldEntry>): Field<String>

    /** Aggregation that produces a JSON array from several rows — used in 1:N relations. */
    fun jsonArrayAgg(element: Field<String>): Field<String>

    /**
     * Same, with the order defined **inside** the aggregation.
     *
     * The order has to go in here, not as the query's `ORDER BY`: the collection comes from a subquery
     * correlated with the parent row, and wrapping it in a derived table — where an `ORDER BY` would fit — puts
     * the correlation out of reach.
     *
     * The default returns the aggregation **without order**; callers check [supportsOrderedAggregation] first.
     */
    fun jsonArrayAgg(element: Field<String>, order: List<SortField<*>>?): Field<String> = jsonArrayAgg(element)

    /** Whether this dialect can order inside the aggregation. */
    fun supportsOrderedAggregation(): Boolean = false

    /**
     * Runs [insert] and returns [row] computed over the inserted row, or `null` if no row went in (conflict
     * discarded). In [row], the columns are those of [inserted], the table under the read alias.
     *
     * @param writtenKey the written primary key values, by column name; whatever is missing is generated by the database
     */
    fun insertAndSelect(
        dsl: DSLContext,
        insert: InsertReturningStep<*>,
        inserted: Table<*>,
        alias: String,
        row: Field<String>,
        writtenKey: Map<String, Any?>,
    ): String? = throw UnsupportedOperationException("dialect ${dsl.dialect()} cannot read back the inserted row")

    /** Database preparation, once at bootstrap (e.g. H2 registers the `TO_BASE64` function). */
    fun initialize(connection: Connection) {
        // nothing to do by default
    }

    companion object {
        /**
         * The JSON dialect of the given database.
         *
         * @throws UnsupportedOperationException for a database without a dialect — only H2 and PostgreSQL are supported
         *         and tested; guessing another's syntax would produce wrong SQL or, worse, truncated JSON
         */
        fun of(dialect: SQLDialect): JsonDialect = when (dialect.family()) {
            SQLDialect.H2 -> H2JsonDialect
            SQLDialect.POSTGRES -> PostgresJsonDialect
            else -> throw UnsupportedOperationException("no JsonDialect for ${dialect.family()}; supported: H2, POSTGRES")
        }
    }
}
